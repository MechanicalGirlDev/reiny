//! Explicit app contracts are independent of the build-time type catalog.

use super::{Exposure, Resolution, describe, rerun_if_changed, resolve_relative};
use anyhow::{Context, Result, bail};
use reiny_core::bindings::{EndpointAddress, validate_port_name};
use serde::Deserialize;
use std::collections::{BTreeMap, BTreeSet};
use std::env;
use std::fmt::Write as _;
use std::path::{Path, PathBuf};

#[derive(Deserialize)]
struct PortManifest {
    version: u32,
    #[serde(default, rename = "in")]
    inputs: BTreeMap<String, PortDef>,
    #[serde(default, rename = "out")]
    outputs: BTreeMap<String, PortDef>,
    #[serde(default)]
    rpc_clients: BTreeMap<String, PortDef>,
    #[serde(default)]
    rpc_servers: BTreeMap<String, PortDef>,
    uses: Option<serde_yaml::Value>,
    provides: Option<serde_yaml::Value>,
}

#[derive(Deserialize)]
#[serde(deny_unknown_fields)]
struct PortDef {
    #[serde(rename = "type")]
    type_name: String,
    response: Option<String>,
    kind: Option<PortKind>,
    #[serde(default, rename = "from")]
    sources: Vec<EndpointAddress>,
}

#[derive(Clone, Copy, Deserialize)]
#[serde(rename_all = "snake_case")]
enum PortKind {
    Stream,
    Rpc,
}

/// Generate `PORTS` from an explicitly selected app YAML contract.
///
/// Call this from `build.rs` alongside [`crate::compile`], then include the separate
/// output at the crate root:
///
/// ```ignore
/// include!(concat!(env!("OUT_DIR"), "/reiny_ports.rs"));
/// ```
///
/// The YAML requires `version: 3`. Named streams live under `in` / `out`;
/// named RPCs live under `rpc_clients` / `rpc_servers` with `type` and `response` FQNs.
/// Inputs and RPC clients require `from: [{namespace: peer, port: output}]`;
/// RPC clients require exactly one source. Outputs cannot declare sources.
/// Each FQN must be in the package's `schema.yaml` catalog. Catalog entries
/// alone never grant a port. Generated constants use the Rust types' `MessageType`
/// wire names and fingerprints, so they work with `reiny-core` on `no_std`.
/// Other runtime metadata is not interpreted here.
pub fn compile_ports(path: impl AsRef<Path>) -> Result<()> {
    let manifest_dir =
        PathBuf::from(env::var("CARGO_MANIFEST_DIR").context("CARGO_MANIFEST_DIR not set")?);
    let path = resolve_relative(&manifest_dir, path.as_ref());
    let resolution = describe(&manifest_dir)?;
    let generated = render_ports(&path, &resolution)?;
    let out_dir = PathBuf::from(env::var("OUT_DIR").context("OUT_DIR not set")?);
    std::fs::write(out_dir.join("reiny_ports.rs"), generated).context("writing reiny_ports.rs")?;
    Ok(())
}

fn render_ports(path: &Path, resolution: &Resolution) -> Result<String> {
    rerun_if_changed(path);
    let text =
        std::fs::read_to_string(path).with_context(|| format!("reading {}", path.display()))?;
    let manifest: PortManifest =
        serde_yaml::from_str(&text).with_context(|| format!("parsing {}", path.display()))?;
    if manifest.version != super::STATIC_PORTS_VERSION {
        bail!(
            "{}: unsupported port contract version {} (expected {})",
            path.display(),
            manifest.version,
            super::STATIC_PORTS_VERSION
        );
    }
    if manifest.uses.is_some() || manifest.provides.is_some() {
        bail!(
            "{}: use rpc_clients/rpc_servers, not uses/provides",
            path.display()
        );
    }
    let mut out = String::from(
        "// @generated by reiny-build — do not edit.\n\
         pub const PORTS: &[::reiny::StaticPort] = &[\n",
    );
    let mut names = BTreeSet::new();
    for (section, input, ports, rpc_section) in [
        ("in", true, &manifest.inputs, false),
        ("out", false, &manifest.outputs, false),
        ("rpc_clients", true, &manifest.rpc_clients, true),
        ("rpc_servers", false, &manifest.rpc_servers, true),
    ] {
        for (name, port) in ports {
            if validate_port_name(name).is_err() {
                bail!(
                    "{}: [{section}.{name}] requires a nonempty port name without '/'",
                    path.display()
                );
            }
            if !names.insert((input, name)) {
                bail!("{}: duplicate port '{name}'", path.display());
            }
            let rpc = match port.kind {
                Some(PortKind::Rpc) => true,
                Some(PortKind::Stream) if rpc_section => {
                    bail!("{}: [{section}.{name}] requires RPC kind", path.display());
                }
                Some(PortKind::Stream) => false,
                None => rpc_section,
            };
            let direction = match (input, rpc) {
                (true, false) => "Input",
                (false, false) => "Output",
                (true, true) => "RpcClient",
                (false, true) => "RpcServer",
            };
            let sources = render_sources(port, input, rpc)
                .with_context(|| format!("{}: [{section}.{name}].from", path.display()))?;
            let ty = port_type_path(resolution, &port.type_name)
                .with_context(|| format!("{}: [{section}.{name}].type", path.display()))?;
            let response = if rpc {
                let response = port.response.as_ref().with_context(|| {
                    format!("{}: [{section}.{name}] requires response", path.display())
                })?;
                let response = port_type_path(resolution, response)
                    .with_context(|| format!("{}: [{section}.{name}].response", path.display()))?;
                format!(
                    "Some(::reiny::PortType {{ ty: <{response} as ::reiny::MessageType>::TYPE_NAME, \
                     schema: <{response} as ::reiny::MessageType>::SCHEMA_FINGERPRINT }})"
                )
            } else {
                if port.response.is_some() {
                    bail!(
                        "{}: [{section}.{name}] stream cannot declare response",
                        path.display()
                    );
                }
                "None".to_owned()
            };
            writeln!(
                out,
                "    ::reiny::StaticPort {{ name: {name:?}, direction: ::reiny::PortDirection::{direction}, \
                 ty: <{ty} as ::reiny::MessageType>::TYPE_NAME, schema: <{ty} as ::reiny::MessageType>::SCHEMA_FINGERPRINT, \
                 response: {response}, sources: &[{sources}] }},"
            )?;
        }
    }
    out.push_str("];\n");
    Ok(out)
}

fn render_sources(port: &PortDef, input: bool, rpc: bool) -> Result<String> {
    if input && (port.sources.is_empty() || (rpc && port.sources.len() != 1)) {
        bail!("requires exact sources (one for RPC)");
    }
    if !input && !port.sources.is_empty() {
        bail!("output cannot declare sources");
    }
    let mut out = String::new();
    let mut unique = BTreeSet::new();
    for source in &port.sources {
        source.validate()?;
        if !unique.insert(source) {
            bail!("duplicate source endpoint");
        }
        write!(
            out,
            "::reiny::StaticEndpointAddress {{ namespace: {:?}, port: {:?} }},",
            source.namespace, source.port,
        )?;
    }
    Ok(out)
}

fn port_type_path(resolution: &Resolution, fqn: &str) -> Result<String> {
    let entry = resolution
        .entries
        .iter()
        .find(|entry| entry.fq_name() == fqn)
        .with_context(|| format!("type '{fqn}' is not in schema.yaml"))?;
    let module = match &entry.exposure {
        Exposure::ExportedTypes => "exported_types".to_owned(),
        Exposure::SharedTypes => "shared_types".to_owned(),
        Exposure::Dependencies(name) => format!("dependencies::{name}"),
    };
    Ok(format!("crate::{module}::{}", entry.alias))
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::manifest_tests::Fixture;

    fn fixture(name: &str) -> Fixture {
        let fixture = Fixture::new(name);
        fixture.write("proto/types.proto", "");
        fixture.write(
            "schema.yaml",
            "version: 3\nschema:\n  project: {name: app}\n  exported_types:\n    State: {proto: proto/types.proto, message: app.State}\n    Request: {proto: proto/types.proto, message: app.Request}\n    Response: {proto: proto/types.proto, message: app.Response}\n",
        );
        fixture
    }

    #[test]
    fn explicit_contract_generates_only_named_grants_and_rust_type_constants() {
        let fixture = fixture("static-ports");
        fixture.write("main.yaml", "invalid yaml: [");
        fixture.write(
            "mcu.yaml",
            "version: 3\nin:\n  receive: {type: app.State, from: [{namespace: peer, port: state}]}\nout:\n  transmit: {type: app.State}\nrpc_clients:\n  call: {type: app.Request, response: app.Response, from: [{namespace: peer, port: serve}]}\nrpc_servers:\n  serve: {type: app.Request, response: app.Response}\n",
        );
        let resolution = describe(fixture.root()).unwrap();
        let generated = render_ports(&fixture.path("mcu.yaml"), &resolution).unwrap();
        assert_eq!(generated.matches("::reiny::StaticPort {").count(), 4);
        for (name, direction) in [
            ("receive", "Input"),
            ("transmit", "Output"),
            ("call", "RpcClient"),
            ("serve", "RpcServer"),
        ] {
            assert!(generated.contains(&format!(
                "name: {name:?}, direction: ::reiny::PortDirection::{direction}"
            )));
        }
        assert!(
            generated.contains("<crate::exported_types::State as ::reiny::MessageType>::TYPE_NAME")
        );
        assert!(generated.contains(
            "<crate::exported_types::Request as ::reiny::MessageType>::SCHEMA_FINGERPRINT"
        ));
        assert!(generated.contains(
            "Some(::reiny::PortType { ty: <crate::exported_types::Response as ::reiny::MessageType>::TYPE_NAME"
        ));
        assert!(!generated.contains("std::"));
        assert!(
            generated.contains(
                "::reiny::StaticEndpointAddress { namespace: \"peer\", port: \"state\" }"
            )
        );
        assert!(
            generated.contains(
                "::reiny::StaticEndpointAddress { namespace: \"peer\", port: \"serve\" }"
            )
        );
    }

    #[test]
    fn catalog_without_app_ports_grants_nothing() {
        let fixture = fixture("empty-static-ports");
        let generated = render_ports(
            &fixture.path("schema.yaml"),
            &describe(fixture.root()).unwrap(),
        )
        .unwrap();
        assert_eq!(generated.matches("::reiny::StaticPort {").count(), 0);
    }

    #[test]
    fn invalid_port_types_and_rpc_contracts_fail_at_generation() {
        let fixture = fixture("invalid-static-ports");
        let resolution = describe(fixture.root()).unwrap();
        for text in [
            "version: 1\n",
            "version: 2\n",
            "version: 3\nuses: {}\n",
            "version: 3\nin: {bad: {type: app.Unknown, from: [{namespace: peer, port: state}]}}\n",
            "version: 3\nrpc_clients: {bad: {type: app.Request, from: [{namespace: peer, port: serve}]}}\n",
            "version: 3\nrpc_servers: {bad: {type: app.Request, response: app.Unknown}}\n",
            "version: 3\nout: {bad: {type: app.State, response: app.Response}}\n",
            "version: 3\nin: {'': {type: app.State}}\n",
            "version: 3\nin: {bad: {type: app.State, kind: typo}}\n",
            "version: 3\nrpc_clients: {bad: {type: app.Request, response: app.Response, kind: stream}}\n",
            "version: 3\nin: {same: {type: app.State, from: [{namespace: peer, port: state}]}}\nrpc_clients: {same: {type: app.Request, response: app.Response, from: [{namespace: peer, port: serve}]}}\n",
            "version: 3\nin: {bad: {type: app.State}}\n",
            "version: 3\nin: {bad: {type: app.State, from: [peer]}}\n",
            "version: 3\nin: {bad: {type: app.State, from: [{namespace: peer, port: state}, {namespace: peer, port: state}]}}\n",
            "version: 3\nin: {bad: {type: app.State, from: [{namespace: '**', port: state}]}}\n",
            "version: 3\nout: {bad: {type: app.State, from: [{namespace: peer, port: state}]}}\n",
            "version: 3\nrpc_clients: {bad: {type: app.Request, response: app.Response, from: [{namespace: peer, port: first}, {namespace: peer, port: second}]}}\n",
        ] {
            fixture.write("ports.yaml", text);
            assert!(
                render_ports(&fixture.path("ports.yaml"), &resolution).is_err(),
                "{text}"
            );
        }
    }

    #[test]
    fn runtime_in_out_rpc_contracts_generate_client_and_service_ports() {
        let fixture = fixture("runtime-rpc-static-ports");
        fixture.write(
            "main.yaml",
            "version: 3\nin:\n  call: {kind: rpc, type: app.Request, response: app.Response, from: [{namespace: peer, port: serve}]}\nout:\n  serve: {kind: rpc, type: app.Request, response: app.Response}\n",
        );
        let generated = render_ports(
            &fixture.path("main.yaml"),
            &describe(fixture.root()).unwrap(),
        )
        .unwrap();
        assert!(generated.contains("name: \"call\", direction: ::reiny::PortDirection::RpcClient"));
        assert!(
            generated.contains("name: \"serve\", direction: ::reiny::PortDirection::RpcServer")
        );
    }
}
