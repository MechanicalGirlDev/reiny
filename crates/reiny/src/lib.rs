/// The one line to put in a shared schema crate's `lib.rs` (`[schema] crate = ...`).
///
/// In workspace mode, the crate that prost-compiles `[shared_types]` and writes the `impl MessageType`s
/// **exactly once** pulls `reiny-build`'s output (`$OUT_DIR/reiny_generated.rs`) in as a library and
/// exposes `shared_types` / `__pb`. A consuming launch only takes a Cargo dependency on that crate and
/// recompiles no protos of its own (the same mechanism `#[reiny::main]` uses to include them).
///
/// ```ignore
/// // myapp-schema/src/lib.rs
/// reiny::schema!();
/// // → myapp_schema::shared_types::* is now available to every other launch
/// ```
#[macro_export]
macro_rules! schema {
    () => {
        #[doc(hidden)]
        mod __reiny_generated {
            include!(concat!(env!("OUT_DIR"), "/reiny_generated.rs"));
        }
        #[allow(unused_imports)]
        pub use __reiny_generated::*;
    };
}

/// Re-exported so the `config()` extension generated by `reiny-build` can read the settings table
/// without the downstream crate carrying a `toml` dependency (hidden, unlike prost).
#[doc(hidden)]
pub use toml as __toml;

/// Called by that generated `config()` when an override in `--config` does not apply, so a typo or
/// a wrong type shows up in the log instead of silently becoming the `[config]` default.
#[doc(hidden)]
pub mod __config {
    /// The key is in `[config]` but the value's type is not the declared one.
    pub fn warn_type(key: &str, expected: &str, value: &toml::Value) {
        tracing::warn!(
            key,
            expected,
            found = value.type_str(),
            "--config: type mismatch, keeping the [config] default"
        );
    }

    /// The key is not in `[config]` at all.
    pub fn warn_unknown(key: &str) {
        tracing::warn!(key, "--config: unknown key ignored (not in [config])");
    }
}

/// reiny's result type. Failures all funnel into [`anyhow::Error`].
pub type Result<T> = anyhow::Result<T>;

/// The namespace (domain) used when none is given.
pub const DEFAULT_DOMAIN: &str = "default";

/// How long a presence query (`publishers()` and friends) waits before giving up. zenoh's `get` default.
const ALIVE_TIMEOUT: Duration = Duration::from_secs(10);
/// The startup "is this id already taken" query. Short enough not to delay startup.
const DUPLICATE_CHECK: Duration = Duration::from_millis(300);

/// A launch's runtime handle. `#[reiny::main]` builds it and hands it over.
///
/// It ties together the engine ([`engine::Engine`]), our instance id, the namespace, and cooperative shutdown.
/// Every data operation uses a declared port name and verifies its compiled type.
pub struct ModuleContext {
    engine: Arc<dyn Engine>,
    id: String,
    domain: String,
    shutdown: Shutdown,
    /// The launch's presence token (merely held; it disappears when the process dies).
    _launch: Guard,
    /// The settings file handed over with `--config <path>`, parsed (`None` if there was none).
    /// The `config()` extension `reiny-build` generates (the per-project `[config]`) reads it.
    config: Option<toml::Table>,
    /// The startup arguments reiny did not interpret (a launch's own `--port`, say).
    extra_args: Vec<String>,
    module: managed::ModuleRuntime,
}

impl ModuleContext {
    /// Build on top of an engine. Declares the `@launch` token and warns when a launch with the same
    /// id is already there (it is not an error — impersonation such as `bag play --as` is deliberate).
    async fn new(
        engine: Arc<dyn Engine>,
        id: String,
        domain: String,
        shutdown: Shutdown,
        config: Option<toml::Table>,
        extra_args: Vec<String>,
    ) -> Result<Self> {
        let launch_key = Key::launch(&domain, Some(&id));
        if engine.caps().liveliness {
            if let Ok(alive) = engine.alive(&launch_key, DUPLICATE_CHECK).await
                && !alive.is_empty()
            {
                tracing::warn!(
                    id,
                    domain,
                    "another launch with the same id is already on the bus; \
                     both will publish under the same keys"
                );
            }
        } else {
            tracing::debug!(
                id,
                domain,
                "engine has no liveliness; launch presence is off"
            );
        }
        let launch = engine.declare_alive(&launch_key)?;
        Ok(Self {
            engine,
            id,
            domain,
            shutdown,
            _launch: launch,
            config,
            extra_args,
            module: managed::ModuleRuntime::default(),
        })
    }

    /// A publisher for the type `T`, emitting to our own `reiny/<domain>/<id>/<T::TYPE_NAME>`.
    /// For `QoS` or latched, use the [`ModuleContext::publisher`] builder.
    #[cfg(any(test, feature = "conformance"))]
    pub(crate) fn publish<T>(&self) -> Result<Publisher<T>>
    where
        T: prost::Message + MessageType,
    {
        self.publisher::<T>().build()
    }

    /// A subscriber for the type `T`, subscribing to `reiny/<domain>/*/<T::TYPE_NAME>` (the same type from
    /// every publisher in the domain). To pick a source or to use latched, use [`ModuleContext::subscriber`].
    #[cfg(any(test, feature = "conformance"))]
    pub(crate) fn subscribe<T>(&self) -> Result<Subscriber<T>>
    where
        T: prost::Message + Default + MessageType,
    {
        self.subscriber::<T>().build()
    }

    /// A publisher builder for the type `T`. Stack `.latched()` and friends, then `.build()`.
    pub(crate) fn publisher<T>(&self) -> PublisherBuilder<'_, T> {
        PublisherBuilder::new(self)
    }

    /// A subscriber builder for the type `T`. Stack `.from(id)` / `.latched()`, then `.build()`.
    pub(crate) fn subscriber<T>(&self) -> SubscriberBuilder<'_, T> {
        SubscriberBuilder::new(self)
    }

    /// The exact endpoints currently publishing `T`, sorted by namespace and port.
    ///
    /// [`ModuleContext::output`] always accompanies a publisher with a liveliness token on the same key
    /// (there is no opt-out — allowing a publisher without one would make this return value
    /// untrustworthy), so an entry disappears the moment the process dies. No application-level
    pub async fn publishers<T: MessageType>(&self) -> Result<Vec<bindings::EndpointAddress>> {
        self.alive_ids(self.key_for(None, T::TYPE_NAME)).await
    }

    /// Exact endpoints alive on the key, sorted and deduplicated by namespace and port.
    async fn alive_ids(&self, key: Key) -> Result<Vec<bindings::EndpointAddress>> {
        let mut ids: Vec<bindings::EndpointAddress> = self
            .engine
            .alive(&key, ALIVE_TIMEOUT)
            .await?
            .into_iter()
            .filter_map(|key| {
                Some(bindings::EndpointAddress {
                    port: key.port()?.to_owned(),
                    namespace: key.source?,
                })
            })
            .collect();
        ids.sort();
        ids.dedup();
        Ok(ids)
    }

    /// Join / leave events for publishers of the type `T`. Publishers already alive when the watch is
    /// declared arrive first as [`PresenceEvent::Joined`] (history is on).
    pub fn watch_publishers<T: MessageType>(&self) -> Result<Presence<T>> {
        self.watch_key(&self.key_for(None, T::TYPE_NAME))
    }

    /// The exact input endpoints currently subscribed to `T`, sorted by namespace and port.
    ///
    /// The counterpart to [`ModuleContext::publishers`], and the answer to the first question of every
    /// bring-up: "I am publishing and nothing reacts — is anyone actually listening?". Every
    /// subscriber carries a token at `reiny/v3/<domain>/<namespace>/@in/<port>/<T>/@sub`,
    /// so this needs no heartbeat either. It identifies the receiver's input port,
    /// independently of the output-source endpoints declared in its bindings.
    pub async fn subscribers<T: MessageType>(&self) -> Result<Vec<bindings::EndpointAddress>> {
        self.alive_ids(self.key_for(None, T::TYPE_NAME).with_chunk(SUB_CHUNK))
            .await
    }

    /// Join / leave events for subscribers of the type `T` (the subscriber side of
    /// [`ModuleContext::watch_publishers`]).
    ///
    /// This is how a publisher waits for its consumer instead of hoping: await the first `Joined`
    /// before the first `send`, and the message that "always gets lost at startup" cannot be.
    pub fn watch_subscribers<T: MessageType>(&self) -> Result<Presence<T>> {
        self.watch_key(&self.key_for(None, T::TYPE_NAME).with_chunk(SUB_CHUNK))
    }

    /// The join / leave stream for the liveliness key `key` (existing declarations arrive as `Joined`).
    pub(crate) fn watch_key<T>(&self, key: &Key) -> Result<Presence<T>> {
        Presence::new(self, key)
    }

    /// Stand up a server for the request type `S`. It puts a queryable on
    /// `reiny/<domain>/<id>/<S::TYPE_NAME>`; take requests off [`RpcServer::recv`] and answer with [`Request::reply`].
    #[cfg(any(test, feature = "conformance"))]
    pub(crate) fn serve<S: Service>(&self) -> Result<RpcServer<S>> {
        self.ensure_standalone()?;
        RpcServer::declare(self, "test")
    }

    /// A caller builder for the request type `S`. Stack `.to(id)` / `.timeout(d)`, then `.build()`.
    pub(crate) fn caller<S: Service>(&self) -> RpcClientBuilder<'_, S> {
        RpcClientBuilder::new(self)
    }

    /// Call `S` once (any server in the domain, at the default timeout).
    /// Sugar over [`ModuleContext::caller`].
    #[cfg(any(test, feature = "conformance"))]
    pub(crate) async fn call<S: Service>(
        &self,
        request: S,
    ) -> std::result::Result<S::Response, CallError> {
        self.caller::<S>()
            .build()
            .map_err(CallError::Engine)?
            .call(request)
            .await
    }

    /// The exact output endpoints currently serving `S`, sorted by namespace and port.
    pub async fn servers<S: Service>(&self) -> Result<Vec<bindings::EndpointAddress>> {
        self.alive_ids(self.key_for(None, S::TYPE_NAME).with_chunk(SERVICE_CHUNK))
            .await
    }

    /// Join / leave events for servers of the request type `S` (the server side of [`ModuleContext::watch_publishers`]).
    pub fn watch_servers<S: Service>(&self) -> Result<Presence<S>> {
        self.watch_key(&self.key_for(None, S::TYPE_NAME).with_chunk(SERVICE_CHUNK))
    }

    /// A subscriber builder for the type **named** `ty` — for a tool that learns the types from the bus
    /// ([`ModuleContext::watch_keys`]) instead of naming them in code. Samples arrive undecoded, fingerprint
    /// unchecked; see [`RawSubscriber`]. A launch names its types and uses [`ModuleContext::subscriber`].
    #[cfg(any(test, feature = "conformance"))]
    pub(crate) fn raw_subscriber(&self, ty: impl Into<String>) -> RawSubscriberBuilder<'_> {
        RawSubscriberBuilder::new(self, ty.into())
    }

    /// Join / leave events, whole keys included, for every presence token matching the pattern `key` —
    /// [`ModuleContext::watch_publishers`] and friends for a tool that does not know the types in advance.
    /// Tokens already alive arrive first as `Joined`.
    ///
    /// [`Key::all`]`(cloudy.domain())` is every publisher of every type; `.with_chunk(`[`engine::SUB_CHUNK`]`)`
    /// / `.with_chunk(`[`engine::SERVICE_CHUNK`]`)` are the subscribers / servers, and
    /// [`Key::launch`]`(domain, None)` is the launches. The one-shot list is `engine().alive(&key, timeout)`.
    pub fn watch_keys(&self, key: &Key) -> Result<RawPresence> {
        RawPresence::new(self, key)
    }

    /// The descriptors live launches announce at `@schema` for the type **named** `ty`: one per
    /// publisher or subscriber of it, two per server (request and response). Sorted by source.
    ///
    /// Only types with a [`MessageType::DESCRIPTOR`] answer — every `reiny-build` generated type has one.
    /// The bytes come back as they were served; decoding them (`prost-reflect`) is the caller's job.
    pub async fn schemas(&self, ty: &str) -> Result<Vec<RawDescriptor>> {
        validate_segment("type", ty)?;
        if !self.engine.caps().query {
            anyhow::bail!("schemas of {ty}: this engine has no query support, which @schema needs");
        }
        let key = self
            .key_for(None, ty)
            .with_chunk(format!("{SCHEMA_CHUNK}/*"));
        let params = QueryParams {
            payload: None,
            attachment: None,
            timeout: ALIVE_TIMEOUT,
        };
        let mut replies = self.engine.query(&key, params)?;
        let mut found = Vec::new();
        while let Some(reply) = replies.next().await {
            let Ok(sample) = reply else { continue };
            let Some(source_port) = sample.key.port().map(str::to_owned) else {
                continue;
            };
            let message = sample
                .key
                .chunk
                .as_deref()
                .and_then(|c| c.strip_prefix(SCHEMA_CHUNK)?.strip_prefix('/'));
            if let (Some(source), Some(message)) = (sample.key.source, message) {
                found.push(RawDescriptor {
                    source,
                    source_port,
                    message: message.to_string(),
                    file_set: sample.payload,
                });
            }
        }
        found.sort();
        Ok(found)
    }

    /// The engine underneath. Reach another engine's own features through `engine().as_any().downcast_ref::<E>()`.
    pub(crate) fn engine(&self) -> &Arc<dyn Engine> {
        &self.engine
    }

    /// A second `ModuleContext` on **another engine**, sharing this one's id / domain / shutdown / config.
    /// The door through which a bridge (`reiny::bridge::forward`) holds "the zenoh `ModuleContext`" and "the
    /// link `ModuleContext`" in one process. The `@launch` token is declared on the new engine as well.
    pub async fn with_engine(&self, engine: Arc<dyn Engine>) -> Result<Self> {
        anyhow::ensure!(
            self.module.bindings.is_some(),
            "module bindings are required"
        );
        let mut cloudy = Self::new(
            engine,
            self.id.clone(),
            self.domain.clone(),
            self.shutdown.clone(),
            self.config.clone(),
            self.extra_args.clone(),
        )
        .await?;
        cloudy.configure_module(self.module.bindings.clone(), None)?;
        Ok(cloudy)
    }

    /// The zenoh session inside. The escape hatch to features reiny does not wrap (queryables,
    /// scouting, attachments, pub/sub on arbitrary keys). `None` when the engine is not zenoh.
    ///
    /// Using it makes zenoh's semver yours — when reiny moves to a new zenoh major, the code that
    /// goes through here comes along for the ride.
    #[cfg(all(test, feature = "zenoh"))]
    #[must_use]
    pub(crate) fn session(&self) -> Option<&zenoh::Session> {
        self.ensure_standalone().ok()?;
        self.engine
            .as_any()
            .downcast_ref::<engine::Zenoh>()
            .map(engine::Zenoh::session)
    }

    /// Our own instance id (`--id` / `--name`, else `CARGO_PKG_NAME`).
    /// A launcher starting the same bin several times numbers them (`pong-1`, `pong-2`, …).
    #[must_use]
    pub fn id(&self) -> &str {
        &self.id
    }

    /// Our own logical namespace (`--domain` / `REINY_DOMAIN`, default [`DEFAULT_DOMAIN`]).
    /// Launches in different domains do not talk to each other, even on the same bus.
    #[must_use]
    pub fn domain(&self) -> &str {
        &self.domain
    }

    /// The startup arguments reiny did not interpret. A launch's own arguments (`--port` …) come from here.
    /// reiny does not reject unknown arguments — it cannot know them, and being strict would break every launch.
    #[must_use]
    pub fn extra_args(&self) -> &[String] {
        &self.extra_args
    }

    /// The current time (Unix seconds). A small convenience for message timestamps.
    #[must_use]
    pub fn now_unix(&self) -> i64 {
        SystemTime::now()
            .duration_since(UNIX_EPOCH)
            .map_or(0, |d| i64::try_from(d.as_secs()).unwrap_or(i64::MAX))
    }

    /// The settings table handed over with `--config` (`None` if there was none). The raw material the
    /// typed `config()` extension `reiny-build` generates layers on top of `[config]`'s defaults.
    #[doc(hidden)]
    #[must_use]
    pub fn config_table(&self) -> Option<&toml::Table> {
        self.config.as_ref()
    }

    /// Wait until shutdown is requested (for a launch running its own loop).
    pub async fn shutdown(&self) {
        self.shutdown.wait().await;
    }

    /// Request shutdown ourselves (idempotent). A subscription loop's `recv` starts returning `None`
    /// and whoever waits in [`ModuleContext::shutdown`] is released.
    pub fn shutdown_now(&self) {
        self.shutdown.trigger();
    }

    /// An explicit type-filtered introspection pattern, never a concrete application route.
    pub(crate) fn key_for(&self, source: Option<&str>, ty: &str) -> Key {
        Key {
            domain: self.domain.clone(),
            source: source.map(str::to_owned),
            endpoint: None,
            ty: Some(ty.to_owned()),
            chunk: None,
        }
    }

    pub(crate) fn shutdown_handle(&self) -> Shutdown {
        self.shutdown.clone()
    }
}

/// Validate that a name can be used as one segment of a key. A wildcard or a separator in there breaks
/// what the key means (it silently goes to a different topic), so reject it at startup.
fn validate_segment(what: &str, value: &str) -> Result<()> {
    if value.is_empty() {
        anyhow::bail!("{what} must not be empty");
    }
    if let Some(bad) = value
        .chars()
        .find(|c| matches!(c, '/' | '*' | '?' | '#' | '$' | '@') || c.is_whitespace())
    {
        anyhow::bail!(
            "{what} '{value}' contains '{bad}': it must be a single key segment \
             (no '/', '*', '?', '#', '$', '@' or whitespace)"
        );
    }
    Ok(())
}

