//! The reiny SDK.
//!
//! Type definitions are generated from `schema.yaml` by `reiny-build`. Communication is
//! authorized separately by runtime YAML ports. Launch through `reiny apply/run` and use
//! named [`ModuleContext::input`], [`ModuleContext::output`], [`ModuleContext::rpc_client`] and [`ModuleContext::rpc_server`].
//! Type definitions alone grant no communication permission.
//!
//! Unnamed communication and transport escape hatches are not application APIs:
//!
//! ```compile_fail
//! fn bypass(cloudy: &reiny::ModuleContext) {
//!     let _ = cloudy.engine();
//! }
//! ```
//!
//! ```compile_fail
//! fn bypass<T: reiny::MessageType + prost::Message>(cloudy: &reiny::ModuleContext) {
//!     let _ = cloudy.publish::<T>();
//! }
//! ```
//!
//! ```ignore
//! use reiny::prelude::*;
//! use crate::exported_types::Ping;        // generated by reiny-build
//! use crate::dependencies::pong::Pong;  // likewise
//!
//! #[reiny::main]
//! async fn main(cloudy: ModuleContext) -> reiny::Result<()> {
//!     let pings = cloudy.output::<Ping>("pings")?;
//!     let mut pongs = cloudy.input::<Pong>("pongs")?;
//!     // ...
//!     Ok(())
//! }
//! ```
//!
//! # Engines
//!
//! [`ModuleContext`] reaches the bus through an [`engine::Engine`]. The default is zenoh
//! ([`engine::Zenoh`], feature `zenoh`). [`engine::Local`] is an in-process bus, so a launch can be
//! tested with no network at all — hand it to [`ModuleContext::open`] through `RuntimeOptions::engine`.
//!

