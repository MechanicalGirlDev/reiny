//! Explicit process-step owner and its all-host admission barrier.

mod admission;
mod channel;
mod executor;
mod preparation;

use super::{
    protocol::{
        Nonce, Prepare, SessionIdentity,
        step::{BoundSteps, MAX_ENTRIES, StepAssignment, StepPreparedReport, StepSessionKey},
    },
    step_wire::invalid,
};
use crate::{component::step::ManagedStepSession, step::StepGraph};
use admission::validate_assignments;
use channel::Channel;
use executor::Executor;
use preparation::{PreparedHosts, activate_hosts, prepare_hosts};
use std::{collections::BTreeMap, time::Duration};
use tokio::{net::TcpStream, time::Instant};

/// One explicitly owned process connection and its immutable expected assignment.
pub struct ProcessStepPeer {
    /// Connected host socket, accepted on an already-bound private listener.
    pub stream: TcpStream,
    /// Exact bootstrap identity generated by the process owner.
    pub identity: SessionIdentity,
    /// One-use OS-random bootstrap nonce.
    pub nonce: Nonce,
    /// Frozen ordinary assignments and transport settings.
    pub prepare: Prepare,
    /// Exact step-node assignments, never inferred from ordinary bindings.
    pub steps: BTreeMap<String, StepAssignment>,
}

/// One authoritative scheduler owner, independent of client observation handles.
///
/// Dropping this owner revokes admission; callers must still reap their owned
/// local processes or retain Unknown containment for remote connections.
pub struct ProcessStepOwner {
    session: ManagedStepSession,
    key: StepSessionKey,
    cleanup: tokio::sync::watch::Receiver<BTreeMap<String, Option<super::protocol::HostOutcome>>>,
}

impl ProcessStepOwner {
    /// Authenticate and prepare every host, validate actual reports, compile the
    /// application graph using actual seeds, then bind/commit/run all hosts.
    ///
    /// `validate` is an app-owned bounded validator of actual prepared reports
    /// and the resolved graph. Draft schemas are checked before preparation.
    /// It cannot grant ordinary port access or replace a prepared component.
    pub async fn prepare(
        peers: Vec<ProcessStepPeer>,
        mut key: StepSessionKey,
        plan: super::ProcessStepPlan,
        initial_time: Duration,
        timeout: Duration,
        validate: impl FnOnce(&BTreeMap<String, StepPreparedReport>, &StepGraph) -> crate::Result<()>,
    ) -> crate::Result<(Self, super::ProcessStepClient)> {
        anyhow::ensure!(
            !peers.is_empty() && peers.len() <= MAX_ENTRIES && !timeout.is_zero(),
            "invalid peers/budget"
        );
        validate_assignments(&peers, &plan, &key)?;
        let deadline = Instant::now().checked_add(timeout).ok_or_else(invalid)?;
        let PreparedHosts {
            mut channels,
            placement,
            reports,
        } = prepare_hosts(peers, deadline, plan.literal_budget()?).await?;
        let graph = plan.resolve(&reports)?;
        validate(&reports, &graph)?;
        drop(reports);
        let plan = crate::step::Plan::compile(graph.clone())?;
        let order = plan.order.clone();
        let wire_graph = super::step_wire::export_graph(&graph)?;
        key.plan_digest = super::step_wire::plan_digest(&wire_graph, initial_time.into())?;
        let (sender, receiver) = tokio::sync::oneshot::channel();
        let bootstrap = graph
            .inputs
            .values()
            .filter_map(|source| match source {
                crate::step::StepSource::PreviousTick { initial, .. } => {
                    Some(initial.as_encoded().len())
                }
                _ => None,
            })
            .try_fold(0usize, usize::checked_add)
            .ok_or_else(invalid)?;
        let retention = std::sync::Arc::new(super::step_client::Retention {
            bootstrap,
            previous: std::sync::atomic::AtomicUsize::new(0),
            available: std::sync::atomic::AtomicUsize::new(0),
        });
        let delayed = graph
            .inputs
            .values()
            .filter_map(|source| match source {
                crate::step::StepSource::PreviousTick { source, .. } => Some(source.clone()),
                _ => None,
            })
            .collect();
        let (cleanup_tx, cleanup) = tokio::sync::watch::channel(
            channels
                .iter()
                .map(|channel| (channel.identity.host_id.0.clone(), None))
                .collect(),
        );
        let executor = Executor {
            channels: receiver,
            ready: None,
            placement,
            key: key.clone(),
            cleanup: cleanup_tx,
            retention: retention.clone(),
            delayed,
            final_ordinal: u32::try_from(order.len() - 1)?,
            run_sequence: None,
            retained: 0,
            next_previous: 0,
        };
        let (session, handle) =
            ManagedStepSession::prepare(graph, initial_time, Box::new(executor))?;
        let bound = BoundSteps {
            session: key.clone(),
            epoch: handle.clock().epoch.get(),
            initial_time: initial_time.into(),
            order,
            graph: wire_graph,
        };
        activate_hosts(&mut channels, &bound, deadline).await?;
        sender.send(channels).map_err(|_| invalid())?;
        session.activate();
        Ok((
            Self {
                session,
                key,
                cleanup,
            },
            super::ProcessStepClient::new(handle, retention),
        ))
    }

    /// Final session identity, including the digest of actual prepared seed data.
    #[must_use]
    pub fn session_key(&self) -> &StepSessionKey {
        &self.key
    }

    /// Revocation/driver completion only; separately join owned process trees.
    pub async fn stop(
        self,
    ) -> Result<BTreeMap<String, Option<super::protocol::HostOutcome>>, tokio::task::JoinError>
    {
        self.session.stop().await?;
        Ok(self.cleanup.borrow().clone())
    }

    /// Retained host cleanup observations. `None` is unknown; even a joined host
    /// outcome does not certify process-tree reaping or remote containment.
    #[must_use]
    pub fn subscribe_cleanup(
        &self,
    ) -> tokio::sync::watch::Receiver<BTreeMap<String, Option<super::protocol::HostOutcome>>> {
        self.cleanup.clone()
    }
}
