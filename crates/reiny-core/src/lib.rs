//! reiny's type vocabulary — `#![no_std]`.
//!
//! Payload identity comes from a Rust type; application authority comes from a named YAML port.
//! This crate holds the type traits ([`MessageType`] / [`Service`]), the descriptor ([`Descriptor`]),
//! the `QoS` vocabulary ([`Qos`]), and the generated static port contract ([`StaticPort`]).
//! reiny proper (tokio / zenoh) is std-only, so the vocabulary was split out down here to let
//! places where zenoh does not run (`reiny-link` on an MCU) share type = topic.
//!
//! Normally you use what `reiny` re-exports. Only the MCU side depends on this crate directly,
//! and there it should be aliased in `Cargo.toml` as `reiny = { package = "reiny-core" }` so that
//! the `impl ::reiny::MessageType for …` emitted by `reiny-build` resolves as-is.
//!
//! `prost` is pulled in `no_std` mode, so **alloc is required** (`Vec` / `String` fields).
// ponytail: alloc is required. Cut the trait when moving to micropb + heapless for alloc-free.

#![no_std]

#[cfg(feature = "bindings")]
extern crate alloc;

#[cfg(feature = "bindings")]
pub mod bindings;

mod qos;

pub use qos::{CongestionControl, Durability, History, Priority, Qos};

use prost::Message;

/// Version of the canonical, transitive message-schema fingerprint contract.
pub const SCHEMA_FINGERPRINT_VERSION: u16 = 2;

/// A named application's communication direction, generated from its YAML ports.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum PortDirection {
    /// Receive messages.
    Input,
    /// Publish messages.
    Output,
    /// Answer service requests.
    RpcServer,
    /// Send service requests.
    RpcClient,
}

/// The wire identity and fingerprint of a generated port's type.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct PortType {
    /// The same fully qualified protobuf name as [`MessageType::TYPE_NAME`].
    pub ty: &'static str,
    /// The same fingerprint as [`MessageType::SCHEMA_FINGERPRINT`].
    pub schema: u64,
}

/// One entry in the static application port table emitted by `reiny-build`.
///
/// Service and client ports include their response contract; input and output ports do not.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct StaticPort {
    /// The YAML port name.
    pub name: &'static str,
    /// The declared communication direction.
    pub direction: PortDirection,
    /// The message or request type's wire name.
    pub ty: &'static str,
    /// The message or request fingerprint.
    pub schema: u64,
    /// The response contract for a service or client.
    pub response: Option<PortType>,
    /// Exact remote output endpoints for inputs and RPC callers; empty for outputs.
    pub sources: &'static [StaticEndpointAddress],
}

/// An allocation-free declared endpoint address for static applications.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct StaticEndpointAddress {
    /// Canonical remote module namespace.
    pub namespace: &'static str,
    /// Declared remote output port name.
    pub port: &'static str,
}

/// The type vocabulary generated from the separate `schema.yaml` catalog.
///
/// `TYPE_NAME` identifies the payload schema, not the communication endpoint.
/// Named outputs use `reiny/v3/<domain>/<namespace>/@out/<port>/<TYPE_NAME>`.
/// Inputs select exact namespace/port pairs; a type alone never grants communication.
/// The same protobuf type yields the same complete name in every crate.
///
/// Engines may render addresses differently. `reiny-link` carries an endpoint hash
/// derived from namespace and port, with type names and fingerprints checked during Hello.
///
/// Type-only implementations are not supported:
///
/// ```compile_fail
/// struct Legacy;
/// impl reiny_core::MessageType for Legacy {
///     const TYPE_NAME: &'static str = "Legacy";
///     const DESCRIPTOR: Option<reiny_core::Descriptor> = None;
/// }
/// ```
///
/// Descriptor availability must also be explicit:
///
/// ```compile_fail
/// struct Legacy;
/// impl reiny_core::MessageType for Legacy {
///     const TYPE_NAME: &'static str = "Legacy";
///     const SCHEMA_FINGERPRINT: u64 = 1;
/// }
/// ```
pub trait MessageType {
    /// The complete protobuf message name (e.g. `ping.Ping`, or `Ping` without a package).
    /// Named endpoint contracts determine
    /// which namespace/port address may be published or received.
    const TYPE_NAME: &'static str;

    /// Schema fingerprint. Types generated by `reiny-build` carry a value computed from the proto
    /// descriptor's transitive message/enum closure.
    ///
    /// Protobuf decoding alone does not establish schema compatibility. The fingerprint rides
    /// in the transport attachment and is checked before decoding; missing or different
    /// fingerprints are rejected. Every implementation supplies the fingerprint of its schema.
    const SCHEMA_FINGERPRINT: u64;

    /// The proto descriptor. Types generated by `reiny-build` point at their own crate's
    /// descriptor set.
    ///
    /// Publishing a type whose value is `Some` makes the publisher declare one queryable beside
    /// its key, at `reiny/v3/<domain>/<namespace>/@out/<port>/<TYPE_NAME>/@schema/<message>`, answering it with that
    /// descriptor set. This is how a running launch **names its own types on the bus**:
    /// `reiny bag record` picks it up and embeds the schema in the MCAP, producing a bag Foxglove
    /// can decode as-is (`docs/design/bag.md` §5).
    ///
    /// `@schema` is a verbatim facet and remains separate from ordinary payload subscriptions.
    /// Every implementation must explicitly declare descriptor availability.
    const DESCRIPTOR: Option<Descriptor>;
}

/// The contents of [`MessageType::DESCRIPTOR`] — the fully qualified proto message name plus the encoded
/// `google.protobuf.FileDescriptorSet` that contains it.
#[derive(Debug, Clone, Copy)]
pub struct Descriptor {
    /// Fully qualified message name (e.g. `hs.RobotState`). Used verbatim as the MCAP schema name.
    pub message: &'static str,
    /// The encoded `FileDescriptorSet`. Holds `message`'s own file and its transitive imports.
    pub file_set: &'static [u8],
}

/// request type → response type. The request type's [`MessageType::TYPE_NAME`] is the type segment of the
/// key.
///
/// `reiny-build` generates the impls from `schema.yaml`'s `schema.services`. Writing one by hand is a
/// single line:
///
/// ```ignore
/// impl reiny::Service for Add { type Response = Sum; }
/// ```
///
/// `Response: MessageType` is required so the reply carries a `SCHEMA_FINGERPRINT` fingerprint of its own.
pub trait Service: MessageType + Message + Default {
    /// The response type.
    type Response: MessageType + Message + Default;
}

#[cfg(test)]
#[allow(clippy::unwrap_used, clippy::expect_used, clippy::panic)] // tests may fail by panicking
mod tests {
    use super::*;
    use prost::DecodeError;
    use prost::bytes::{Buf, BufMut};
    use prost::encoding::{DecodeContext, WireType, skip_field};

    /// Empty test messages with explicit topic metadata.
    macro_rules! empty_message {
        ($name:ident) => {
            #[derive(Debug, Default, Clone, PartialEq, Eq)]
            struct $name;

            impl Message for $name {
                fn encode_raw(&self, _buf: &mut impl BufMut) {}
                fn merge_field(
                    &mut self,
                    tag: u32,
                    wire_type: WireType,
                    buf: &mut impl Buf,
                    ctx: DecodeContext,
                ) -> Result<(), DecodeError> {
                    skip_field(wire_type, tag, buf, ctx)
                }
                fn encoded_len(&self) -> usize {
                    0
                }
                fn clear(&mut self) {}
            }
        };
    }

    empty_message!(Add);
    empty_message!(Sum);

    impl MessageType for Add {
        const TYPE_NAME: &'static str = "Add";
        const SCHEMA_FINGERPRINT: u64 = 1;
        const DESCRIPTOR: Option<Descriptor> = None;
    }

    impl MessageType for Sum {
        const TYPE_NAME: &'static str = "Sum";
        const SCHEMA_FINGERPRINT: u64 = 2;
        const DESCRIPTOR: Option<Descriptor> = None;
    }

    impl Service for Add {
        type Response = Sum;
    }

    /// A service addresses itself by its *request* type; the response type is reachable through
    /// the associated type and is a `MessageType` in its own right (so replies carry a fingerprint).
    #[test]
    fn service_addresses_by_request_type() {
        assert_eq!(<Add as Service>::Response::TYPE_NAME, "Sum");
        // The key segment is the request type's, never the response type's.
        assert_ne!(Add::TYPE_NAME, <Add as Service>::Response::TYPE_NAME);
    }

    /// Explicit metadata uses the same shape as `reiny-build` output.
    #[test]
    fn descriptor_and_schema_are_overridable() {
        struct Generated;

        const FILE_SET: &[u8] = b"not-a-real-descriptor-set";

        impl MessageType for Generated {
            const TYPE_NAME: &'static str = "hs.Generated";
            const SCHEMA_FINGERPRINT: u64 = 0xdead_beef;
            const DESCRIPTOR: Option<Descriptor> = Some(Descriptor {
                message: "hs.Generated",
                file_set: FILE_SET,
            });
        }

        assert_eq!(Generated::SCHEMA_FINGERPRINT, 0xdead_beef);
        let d = Generated::DESCRIPTOR.expect("DESCRIPTOR was set to Some");
        assert_eq!(d.message, "hs.Generated");
        assert_eq!(d.file_set, FILE_SET);
    }
}
