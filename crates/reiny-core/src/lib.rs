//! reiny's type vocabulary — `#![no_std]`.
//!
//! Payload identity comes from a Rust type; application authority comes from a named YAML port.
//! This crate holds the type traits ([`Topic`] / [`Service`]), the descriptor ([`Descriptor`]),
//! the `QoS` vocabulary ([`Qos`]), and the generated static port contract ([`StaticPort`]).
//! reiny proper (tokio / zenoh) is std-only, so the vocabulary was split out down here to let
//! places where zenoh does not run (`reiny-link` on an MCU) share type = topic.
//!
//! Normally you use what `reiny` re-exports. Only the MCU side depends on this crate directly,
//! and there it should be aliased in `Cargo.toml` as `reiny = { package = "reiny-core" }` so that
//! the `impl ::reiny::Topic for …` emitted by `reiny-build` resolves as-is.
//!
//! `prost` is pulled in `no_std` mode, so **alloc is required** (`Vec` / `String` fields).
// ponytail: alloc is required. Cut the trait when moving to micropb + heapless for alloc-free.

#![no_std]

#[cfg(feature = "bindings")]
extern crate alloc;

#[cfg(feature = "bindings")]
pub mod bindings;

mod qos;

pub use qos::{Durability, History, Priority, Qos, Reliability};

use prost::Message;

/// A named application's communication direction, generated from its YAML ports.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum PortDirection {
    /// Receive messages.
    Input,
    /// Publish messages.
    Output,
    /// Answer service requests.
    Service,
    /// Send service requests.
    Client,
}

/// The wire identity and fingerprint of a generated port's type.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct PortType {
    /// The same short wire name as [`Topic::TYPE`].
    pub ty: &'static str,
    /// The same fingerprint as [`Topic::SCHEMA`].
    pub schema: u64,
}

/// One entry in the static application port table emitted by `reiny-build`.
///
/// Service and client ports include their response contract; input and output ports do not.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct StaticPort {
    /// The YAML port name.
    pub name: &'static str,
    /// The declared communication direction.
    pub direction: PortDirection,
    /// The message or request type's wire name.
    pub ty: &'static str,
    /// The message or request fingerprint.
    pub schema: u64,
    /// The response contract for a service or client.
    pub response: Option<PortType>,
}

/// The type vocabulary generated from the separate `schema.yaml` catalog.
///
/// The type `Ping` identifies the wire segment in `reiny/<domain>/<id>/Ping`. Named runtime
/// inputs select an exact publisher namespace; a type alone never grants communication.
/// `<id>` is the possibly nested instance namespace, and `TYPE` the type segment of the key
/// (e.g. `Ping`). The same type yields the same `TYPE` whichever crate it is compiled in.
///
/// Engines other than zenoh do not necessarily render that key shape — `reiny-link` puts a 32-bit
/// hash of `TYPE` on the wire and has no `<domain>`. The single thing they all share is that
/// `TYPE` is the address.
///
/// Type-only implementations are not supported:
///
/// ```compile_fail
/// struct Legacy;
/// impl reiny_core::Topic for Legacy {
///     const TYPE: &'static str = "Legacy";
///     const DESCRIPTOR: Option<reiny_core::Descriptor> = None;
/// }
/// ```
///
/// Descriptor availability must also be explicit:
///
/// ```compile_fail
/// struct Legacy;
/// impl reiny_core::Topic for Legacy {
///     const TYPE: &'static str = "Legacy";
///     const SCHEMA: u64 = 1;
/// }
/// ```
pub trait Topic {
    /// The type segment of the topic key (e.g. `Ping`). Named endpoint contracts determine
    /// which `reiny/<domain>/<id>/<TYPE>` address may be published or received.
    const TYPE: &'static str;

    /// Schema fingerprint. Types generated by `reiny-build` carry a value computed from the proto
    /// descriptor.
    ///
    /// **Why it exists.** `TYPE` is the bare type name with the proto package stripped, so the
    /// topic namespace stays flat and a same-named type from another project can land on the same
    /// topic. protobuf is permissive, so when the field numbers happen to line up the **decode
    /// succeeds and the message is silently wrong**. The fingerprint is the only safety valve
    /// against that flatness: it rides in the zenoh attachment on publish and is checked on
    /// subscribe. Missing or different fingerprints are rejected before protobuf decoding.
    /// Every implementation must supply the fingerprint of its schema.
    const SCHEMA: u64;

    /// The proto descriptor. Types generated by `reiny-build` point at their own crate's
    /// descriptor set.
    ///
    /// Publishing a type whose value is `Some` makes the publisher declare one queryable beside
    /// its key, at `reiny/<domain>/<id>/<TYPE>/@schema/<message>`, answering it with that
    /// descriptor set. This is how a running launch **names its own types on the bus**:
    /// `reiny bag record` picks it up and embeds the schema in the MCAP, producing a bag Foxglove
    /// can decode as-is (`docs/design/bag.md` §5).
    ///
    /// `@schema` is a zenoh verbatim chunk, so it is invisible both to a `reiny/<domain>/**`
    /// subscriber and to a `reiny/<domain>/*/*` recording — the type's own topic stays clean.
    /// Every implementation must explicitly declare descriptor availability.
    const DESCRIPTOR: Option<Descriptor>;
}

/// The contents of [`Topic::DESCRIPTOR`] — the fully qualified proto message name plus the encoded
/// `google.protobuf.FileDescriptorSet` that contains it.
#[derive(Debug, Clone, Copy)]
pub struct Descriptor {
    /// Fully qualified message name (e.g. `hs.RobotState`). Used verbatim as the MCAP schema name.
    pub message: &'static str,
    /// The encoded `FileDescriptorSet`. Holds `message`'s own file and its transitive imports.
    pub file_set: &'static [u8],
}

/// request type → response type. The request type's [`Topic::TYPE`] is the type segment of the
/// key.
///
/// `reiny-build` generates the impls from `schema.yaml`'s `schema.services`. Writing one by hand is a
/// single line:
///
/// ```ignore
/// impl reiny::Service for Add { type Response = Sum; }
/// ```
///
/// `Response: Topic` is required so the reply carries a `SCHEMA` fingerprint of its own.
pub trait Service: Topic + Message + Default {
    /// The response type.
    type Response: Topic + Message + Default;
}

#[cfg(test)]
#[allow(clippy::unwrap_used, clippy::expect_used, clippy::panic)] // tests may fail by panicking
mod tests {
    use super::*;
    use prost::DecodeError;
    use prost::bytes::{Buf, BufMut};
    use prost::encoding::{DecodeContext, WireType, skip_field};

    /// Empty test messages with explicit topic metadata.
    macro_rules! empty_message {
        ($name:ident) => {
            #[derive(Debug, Default, Clone, PartialEq, Eq)]
            struct $name;

            impl Message for $name {
                fn encode_raw(&self, _buf: &mut impl BufMut) {}
                fn merge_field(
                    &mut self,
                    tag: u32,
                    wire_type: WireType,
                    buf: &mut impl Buf,
                    ctx: DecodeContext,
                ) -> Result<(), DecodeError> {
                    skip_field(wire_type, tag, buf, ctx)
                }
                fn encoded_len(&self) -> usize {
                    0
                }
                fn clear(&mut self) {}
            }
        };
    }

    empty_message!(Add);
    empty_message!(Sum);

    impl Topic for Add {
        const TYPE: &'static str = "Add";
        const SCHEMA: u64 = 1;
        const DESCRIPTOR: Option<Descriptor> = None;
    }

    impl Topic for Sum {
        const TYPE: &'static str = "Sum";
        const SCHEMA: u64 = 2;
        const DESCRIPTOR: Option<Descriptor> = None;
    }

    impl Service for Add {
        type Response = Sum;
    }

    /// A service addresses itself by its *request* type; the response type is reachable through
    /// the associated type and is a `Topic` in its own right (so replies carry a fingerprint).
    #[test]
    fn service_addresses_by_request_type() {
        assert_eq!(<Add as Service>::Response::TYPE, "Sum");
        // The key segment is the request type's, never the response type's.
        assert_ne!(Add::TYPE, <Add as Service>::Response::TYPE);
    }

    /// Explicit metadata uses the same shape as `reiny-build` output.
    #[test]
    fn descriptor_and_schema_are_overridable() {
        struct Generated;

        const FILE_SET: &[u8] = b"not-a-real-descriptor-set";

        impl Topic for Generated {
            const TYPE: &'static str = "Generated";
            const SCHEMA: u64 = 0xdead_beef;
            const DESCRIPTOR: Option<Descriptor> = Some(Descriptor {
                message: "hs.Generated",
                file_set: FILE_SET,
            });
        }

        assert_eq!(Generated::SCHEMA, 0xdead_beef);
        let d = Generated::DESCRIPTOR.expect("DESCRIPTOR was set to Some");
        assert_eq!(d.message, "hs.Generated");
        assert_eq!(d.file_set, FILE_SET);
    }
}
